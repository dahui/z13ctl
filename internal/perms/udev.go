package perms

// udev.go — the rules file: the persistent half of the grants, applied by
// udev on real kernel events (a boot, a reattached keyboard cover).

import (
	"fmt"
	"strings"
)

// Marker is the line every file setup writes carries. setup --remove deletes
// only files that have it, and a pre-2.0 z13ctl setup's marker is how
// cleanupOldArtifacts recognises its leftovers; this one is how a future
// release will recognise ours.
const Marker = "# Generated by: voltaire setup"

// Header describes the run that wrote a file, so a reader (and the boot pass)
// can tell which machine and release it was written for.
type Header struct {
	Device  string
	Group   string
	Version string
}

func (h Header) lines() string {
	return fmt.Sprintf("%s\n# Device: %s, group: %s, voltaire %s\n", Marker, h.Device, h.Group, h.Version)
}

// ParseHeader reads the device id and group back from a file setup wrote,
// "" for each when the file has no header.
func ParseHeader(content string) (device, group string) {
	for _, line := range strings.Split(content, "\n") {
		rest, ok := strings.CutPrefix(line, "# Device: ")
		if !ok {
			continue
		}
		device, rest, _ = strings.Cut(rest, ", group: ")
		group, _, _ = strings.Cut(rest, ",")
		return device, group
	}
	return "", ""
}

// Rules renders the udev rules file.
//
// Every sysfs rule runs the same shell loop, skipping a missing file with
// `|| continue` rather than `&&`: with `&&` a missing last file left the
// loop's status at 1 and udev logged a failed RUN at every boot. "$$" is
// udev's escape for a literal dollar sign; a bare "$f" expands to nothing and
// the loop silently grants nothing.
//
// hidraw interfaces are matched as ENV{ID_USB_INTERFACE_NUM}, which udev's
// usb_id sets on the node itself, never as ATTRS{bInterfaceNumber}: every
// ATTRS key in one rule must match on the same parent, and bInterfaceNumber
// lives on the USB interface while idVendor/idProduct live on the device
// above it. That form matched nothing, and the first boot after it shipped
// (2026-11-15) left the Z13's keyboard dark. Input nodes narrow to a USB
// interface with ENV keys for the same reason.
func (g Grants) Rules(h Header) string {
	var b strings.Builder
	b.WriteString("# 99-voltaire.rules — voltaire's device access on this machine.\n")
	b.WriteString(h.lines())
	b.WriteString("# Rewritten by `sudo voltaire setup`; removed by `sudo voltaire setup --remove`.\n")
	b.WriteString("# Grants the group only what this machine's device file needs; the boot pass\n")
	b.WriteString("# (voltaire-perms.service) applies the same grants to attributes that appear\n")
	b.WriteString("# after their udev event.\n")

	for _, r := range g.HIDRaw {
		v, p, _ := strings.Cut(r.USB, ":")
		mode := "0640"
		if r.Write {
			mode = "0660"
		}
		fmt.Fprintf(&b, "\n# %s\n", r.Why)
		fmt.Fprintf(&b, `SUBSYSTEM=="hidraw", ATTRS{idVendor}=="%s", ATTRS{idProduct}=="%s", ENV{ID_USB_INTERFACE_NUM}=="%02x", MODE="%s", GROUP="%s"`+"\n",
			v, p, r.Interface, mode, h.Group)
	}

	for _, in := range g.Input {
		fmt.Fprintf(&b, "\n# %s (read only)\n", in.Why)
		usb := ""
		if in.USB != "" {
			v, p, _ := strings.Cut(in.USB, ":")
			usb = fmt.Sprintf(`ENV{ID_VENDOR_ID}==%q, ENV{ID_MODEL_ID}==%q, ENV{ID_USB_INTERFACE_NUM}=="%02x", `, v, p, in.Interface)
		}
		if in.DMI == nil {
			fmt.Fprintf(&b, `ACTION=="add", SUBSYSTEM=="input", KERNEL=="event*", ATTRS{name}=="%s", %sENV{ID_INPUT_KEYBOARD}!="1", MODE="0640", GROUP="%s"`+"\n",
				in.Name, usb, h.Group)
			continue
		}
		// A keyboard node the device file opted in: scoped to that file's DMI
		// match instead of the keyboard guard, so it can never apply on
		// another machine.
		for _, m := range in.DMI {
			product := m.Product
			if product == "" {
				product = m.ProductPrefix + "*"
			}
			fmt.Fprintf(&b, `ACTION=="add", SUBSYSTEM=="input", KERNEL=="event*", ATTRS{name}=="%s", %sATTR{[dmi/id]sys_vendor}=="%s", ATTR{[dmi/id]product_name}=="%s", MODE="0640", GROUP="%s"`+"\n",
				in.Name, usb, m.Vendor, product, h.Group)
		}
	}

	for _, s := range g.Sysfs {
		if s.Udev == "" {
			paths := make([]string, len(s.Files))
			for i, f := range s.Files {
				paths[i] = s.Dir + "/" + f
			}
			fmt.Fprintf(&b, "\n# %s: %s\n# No udev rule can reach %s; voltaire-perms.service grants it at boot.\n",
				s.Capability, s.Why, strings.Join(paths, " "))
			continue
		}
		base := s.Dir
		if s.EventDir {
			base = "/sys%p"
		}
		paths := make([]string, len(s.Files))
		for i, f := range s.Files {
			paths[i] = base + "/" + f
		}
		mode := "g+r"
		if s.Write {
			mode = "g+w"
		}
		fmt.Fprintf(&b, "\n# %s: %s\n", s.Capability, s.Why)
		fmt.Fprintf(&b, `%s, RUN+="/bin/sh -c 'for f in %s; do [ -e \"$$f\" ] || continue; chgrp %s \"$$f\" && chmod %s \"$$f\"; done'"`+"\n",
			s.Udev, strings.Join(paths, " "), h.Group, mode)
	}
	return b.String()
}
