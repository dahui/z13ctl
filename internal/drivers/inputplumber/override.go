package inputplumber

// override.go — the one InputPlumber file voltaire writes, and only when the
// user asks (voltaire setup --inputplumber-passthrough): a copy of
// InputPlumber's own device config for this machine with `passthrough: true`
// on the hidraw source carrying the lighting, so InputPlumber leaves that
// node visible (docs/decisions/0178).
//
// The copy is regenerated from the installed config on every setup run and
// at boot, never kept: a copy kept would hide every later upstream change to
// that config. The edit is one inserted line, checked by parsing both files
// and requiring that the only difference is that key. A config the edit
// cannot be applied to cleanly gets no override, so the worst case is
// InputPlumber's own file, never a broken one.
//
// InputPlumber reads /etc/inputplumber/devices.d before its data directory
// and sorts the two together by file name, so an override with the upstream
// file's name is the one it loads.

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"reflect"
	"slices"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

// OverrideMarker is the first line of every override setup writes. Only a
// file carrying it is setup's to rewrite or remove.
const OverrideMarker = "# Generated by: voltaire setup --inputplumber-passthrough"

// Where InputPlumber's configs live. Vars so tests can point them elsewhere.
var (
	// DataDirs are InputPlumber's data directories in its own preference
	// order (the XDG defaults it uses); it reads devices from the first that
	// exists.
	DataDirs = []string{"/usr/local/share/inputplumber", "/usr/share/inputplumber"}
	// OverrideDir is where an administrator's device configs go; InputPlumber
	// prefers a file here over the same name in its data directory.
	OverrideDir = "/etc/inputplumber/devices.d"
	// DMIDir is the firmware identity InputPlumber matches configs against.
	DMIDir = "/sys/class/dmi/id"
)

// UpstreamDir is the device-config directory InputPlumber reads, or "" when
// InputPlumber is not installed.
func UpstreamDir() string {
	for _, d := range DataDirs {
		if fi, err := os.Stat(d); err == nil && fi.IsDir() {
			return d + "/devices"
		}
	}
	return ""
}

// HIDRawSource is a hidraw source device in a composite device config.
type HIDRawSource struct {
	Vendor, Product uint16
	Interface       int
}

func (s HIDRawSource) String() string {
	return fmt.Sprintf("%04x:%04x interface %d", s.Vendor, s.Product, s.Interface)
}

// Passthrough returns config with `passthrough: true` on every hidraw source
// that is one of srcs, and whether any source matched. A source already
// passed through is left as it is, so patched equals config when there is
// nothing to do. An error means the edit could not be made and checked; the
// caller writes nothing then.
func Passthrough(config []byte, srcs []HIDRawSource) (patched []byte, matched bool, err error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(config, &doc); err != nil {
		return nil, false, err
	}
	items := sourceItems(&doc)
	type edit struct {
		line, col int    // 1-based, where the text goes
		cut       int    // bytes replaced there
		text      string // what goes there
	}
	var edits []edit
	var hit []int
	for i, item := range items {
		if !matchesSource(item, srcs) {
			continue
		}
		hit = append(hit, i)
		if v := mapValue(item, "passthrough"); v != nil {
			var on bool
			if v.Decode(&on) == nil && on {
				continue
			}
			edits = append(edits, edit{v.Line, v.Column, len(v.Value), "true"})
			continue
		}
		if item.Style&yaml.FlowStyle != 0 || len(item.Content) == 0 {
			return nil, true, fmt.Errorf("source %d is not a block mapping", i)
		}
		k := item.Content[0]
		edits = append(edits, edit{k.Line, k.Column, 0,
			"passthrough: true # voltaire: leave the lighting interface visible\n" +
				strings.Repeat(" ", k.Column-1)})
	}
	if len(hit) == 0 {
		return config, false, nil
	}
	if len(edits) == 0 {
		return config, true, nil
	}

	lines := strings.SplitAfter(string(config), "\n")
	// Bottom up, so an edit never moves the position of one still to make.
	slices.SortFunc(edits, func(a, b edit) int { return b.line - a.line })
	for _, e := range edits {
		if e.line < 1 || e.line > len(lines) {
			return nil, true, fmt.Errorf("line %d out of range", e.line)
		}
		l := lines[e.line-1]
		at := e.col - 1
		if at < 0 || at+e.cut > len(l) || !isASCII(l[:at]) {
			return nil, true, fmt.Errorf("line %d: cannot place the edit", e.line)
		}
		lines[e.line-1] = l[:at] + e.text + l[at+e.cut:]
	}
	patched = []byte(strings.Join(lines, ""))
	if err := checkOnlyPassthrough(config, patched, hit); err != nil {
		return nil, true, err
	}
	return patched, true, nil
}

// checkOnlyPassthrough parses both files and requires that the patched one
// is the original with passthrough true on the sources at hit, and nothing
// else changed.
func checkOnlyPassthrough(orig, patched []byte, hit []int) error {
	var a, b map[string]any
	if err := yaml.Unmarshal(orig, &a); err != nil {
		return err
	}
	if err := yaml.Unmarshal(patched, &b); err != nil {
		return fmt.Errorf("the edited config does not parse: %w", err)
	}
	srcs, _ := a["source_devices"].([]any)
	for _, i := range hit {
		m, ok := srcs[i].(map[string]any)
		if !ok {
			return fmt.Errorf("source %d is not a mapping", i)
		}
		m["passthrough"] = true
	}
	if !reflect.DeepEqual(a, b) {
		return errors.New("the edited config differs by more than the passthrough key")
	}
	return nil
}

// sourceItems is the config's source_devices entries.
func sourceItems(doc *yaml.Node) []*yaml.Node {
	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return nil
	}
	seq := mapValue(doc.Content[0], "source_devices")
	if seq == nil || seq.Kind != yaml.SequenceNode {
		return nil
	}
	return seq.Content
}

// matchesSource reports whether a source_devices entry is a hidraw source
// naming exactly one of srcs: vendor, product and interface all given.
func matchesSource(item *yaml.Node, srcs []HIDRawSource) bool {
	h := mapValue(item, "hidraw")
	if h == nil {
		return false
	}
	v, okV := number(mapValue(h, "vendor_id"))
	p, okP := number(mapValue(h, "product_id"))
	n, okN := number(mapValue(h, "interface_num"))
	if !okV || !okP || !okN {
		return false
	}
	for _, s := range srcs {
		if uint64(s.Vendor) == v && uint64(s.Product) == p && uint64(s.Interface) == n {
			return true
		}
	}
	return false
}

// number reads an integer scalar, 0x-prefixed or decimal.
func number(n *yaml.Node) (uint64, bool) {
	if n == nil || n.Kind != yaml.ScalarNode {
		return 0, false
	}
	v, err := strconv.ParseUint(n.Value, 0, 32)
	return v, err == nil
}

func isASCII(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= 0x80 {
			return false
		}
	}
	return true
}

// DMI is the machine's firmware identity, by InputPlumber's field names.
type DMI map[string]string

// dmiFields are the dmi_data keys InputPlumber reads from /sys/class/dmi/id.
var dmiFields = []string{
	"bios_release", "bios_vendor", "bios_version", "board_name", "board_vendor",
	"product_name", "product_version", "product_sku", "sys_vendor",
}

// ReadDMI reads the identity InputPlumber matches against; an unreadable
// field is empty.
func ReadDMI() DMI {
	d := DMI{}
	for _, f := range dmiFields {
		if b, err := os.ReadFile(DMIDir + "/" + f); err == nil {
			d[f] = strings.TrimSpace(string(b))
		}
	}
	return d
}

// ConfigMatches reports whether InputPlumber could use config on this
// machine: no matches list, or any dmi_data entry whose fields all match (as
// globs, like InputPlumber's). What cannot be judged from DMI — a udev match,
// a CPU field, a brace pattern — counts as a match: an override that is never
// loaded costs nothing, while a missing one leaves the lighting hidden.
func ConfigMatches(config []byte, dmi DMI) bool {
	var c struct {
		Matches []struct {
			DMIData map[string]string `yaml:"dmi_data"`
			Udev    any               `yaml:"udev"`
		} `yaml:"matches"`
	}
	if yaml.Unmarshal(config, &c) != nil {
		return false
	}
	if len(c.Matches) == 0 {
		return true
	}
	for _, m := range c.Matches {
		if m.Udev != nil {
			return true
		}
		if len(m.DMIData) == 0 {
			continue
		}
		if dmiEntryMatches(m.DMIData, dmi) {
			return true
		}
	}
	return false
}

func dmiEntryMatches(want map[string]string, dmi DMI) bool {
	for field, pattern := range want {
		if !slices.Contains(dmiFields, field) || strings.Contains(pattern, "{") {
			continue // judged as matching: see ConfigMatches
		}
		ok, err := path.Match(pattern, dmi[field])
		if err == nil && !ok {
			return false
		}
	}
	return true
}

// OverrideFile is one override setup would write.
type OverrideFile struct {
	Name    string // the upstream file's name, which is what makes it win
	From    string // the upstream file it was made from
	Content []byte
}

// OverridePlan is what bringing OverrideDir in line with the user's choice
// takes.
type OverridePlan struct {
	Write     []OverrideFile // new or changed
	Unchanged []string       // already exactly what would be written
	Remove    []string       // setup's own, no longer wanted
	Foreign   []string       // a file of the same name setup did not write: left alone
	Failed    []string       // a config the edit could not be made to, with why
}

// Changed reports whether applying the plan alters any file.
func (p OverridePlan) Changed() bool { return len(p.Write) > 0 || len(p.Remove) > 0 }

// Wanted reports whether InputPlumber, as installed, hides one of srcs on
// this machine: whether an override would do anything.
func (p OverridePlan) Wanted() bool {
	return len(p.Write) > 0 || len(p.Unchanged) > 0 || len(p.Foreign) > 0
}

// PlanOverrides works out the overrides for srcs on this machine. want false
// plans the removal of every override setup wrote. The upstream configs are
// read from upstream (UpstreamDir), never from OverrideDir, so an override
// is always made from InputPlumber's current file.
func PlanOverrides(upstream string, srcs []HIDRawSource, dmi DMI, want bool) (OverridePlan, error) {
	var p OverridePlan
	desired := map[string]bool{}
	if want && upstream != "" && len(srcs) > 0 {
		files, err := filepath.Glob(upstream + "/*.yaml")
		if err != nil {
			return p, err
		}
		for _, f := range files {
			data, err := os.ReadFile(f)
			if err != nil || !ConfigMatches(data, dmi) {
				continue
			}
			patched, matched, err := Passthrough(data, srcs)
			switch {
			case !matched:
				continue
			case err != nil:
				p.Failed = append(p.Failed, fmt.Sprintf("%s: %v", f, err))
				continue
			case bytes.Equal(patched, data):
				continue // InputPlumber already passes it through
			}
			name := filepath.Base(f)
			desired[name] = true
			content := overrideContent(f, srcs, patched)
			existing, err := os.ReadFile(OverrideDir + "/" + name)
			switch {
			case err != nil:
				p.Write = append(p.Write, OverrideFile{name, f, content})
			case !IsOverride(existing):
				p.Foreign = append(p.Foreign, OverrideDir+"/"+name)
			case bytes.Equal(existing, content):
				p.Unchanged = append(p.Unchanged, OverrideDir+"/"+name)
			default:
				p.Write = append(p.Write, OverrideFile{name, f, content})
			}
		}
	}
	for _, name := range Overrides() {
		if !desired[name] {
			p.Remove = append(p.Remove, OverrideDir+"/"+name)
		}
	}
	return p, nil
}

// Overrides is the file names in OverrideDir that setup wrote.
func Overrides() []string {
	files, _ := filepath.Glob(OverrideDir + "/*.yaml")
	var out []string
	for _, f := range files {
		if data, err := os.ReadFile(f); err == nil && IsOverride(data) {
			out = append(out, filepath.Base(f))
		}
	}
	return out
}

// IsOverride reports whether a file is one setup wrote.
func IsOverride(data []byte) bool {
	return bytes.HasPrefix(data, []byte(OverrideMarker+"\n"))
}

func overrideContent(from string, srcs []HIDRawSource, patched []byte) []byte {
	names := make([]string, len(srcs))
	for i, s := range srcs {
		names[i] = s.String()
	}
	header := OverrideMarker + "\n" +
		"# InputPlumber's " + from + " with passthrough on the lighting\n" +
		"# interface (" + strings.Join(names, ", ") + "), so voltaire can reach it.\n" +
		"# Remade from that file by every voltaire setup run and at boot; edits here\n" +
		"# are lost. Remove: sudo voltaire setup --inputplumber-passthrough=false\n\n"
	return append([]byte(header), patched...)
}

// Apply carries out the plan.
func (p OverridePlan) Apply() error {
	var errs []error
	if len(p.Write) > 0 {
		if err := os.MkdirAll(OverrideDir, 0o755); err != nil {
			return err
		}
	}
	for _, f := range p.Write {
		if err := os.WriteFile(OverrideDir+"/"+f.Name, f.Content, 0o644); err != nil {
			errs = append(errs, err)
		}
	}
	for _, f := range p.Remove {
		if err := os.Remove(f); err != nil && !errors.Is(err, os.ErrNotExist) {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}
